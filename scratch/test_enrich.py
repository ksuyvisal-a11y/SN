def enrich_km(text: str) -> str:
    res = text.strip()
    # Clean double punctuation like ?!។ or ?។
    res = re.sub(r'[\?!\s]+[។.]*$', '?!', res)
    for pat, rep in KHMER_SHORT_EXPANSIONS:
        if re.search(pat, res):
            res = re.sub(pat, rep, res)
            break
    return res

with open('scratch_shorts.txt', encoding='utf-8') as f:
    lines = f.readlines()

with open('scratch_enrich_out.txt', 'w', encoding='utf-8') as out:
    for line in lines:
        if line.startswith("ID "):
            current_id = line.strip()
        elif line.strip().startswith("KM:"):
            km = line.strip()[3:].strip()
            enriched = enrich_km(km)
            out.write(f"{current_id}\n")
            out.write(f"  Old: {km}\n")
            out.write(f"  New: {enriched}\n")
            out.write("-" * 50 + "\n")
